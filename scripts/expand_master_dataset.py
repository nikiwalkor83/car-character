def main():
    # 1. Read existing cars
    with open("cars_metadata.json", "r") as f:
        existing_cars = json.load(f)

    existing_names = set(c["Car name"].strip().lower() for c in existing_cars)
    print(f"Loaded {len(existing_cars)} existing cars.")

    # 2. Validate additions
    added_count = 0
    added_per_decade = {}

    for car in NEW_CARS:
        name_key = car["Car name"].strip().lower()
        if name_key in existing_names:
            print(f"WARNING: Duplicate found: {car['Car name']}, skipping!")
            continue
        existing_cars.append(car)
        existing_names.add(name_key)
        added_count += 1
        dec = car["Decade"]
        added_per_decade[dec] = added_per_decade.get(dec, 0) + 1

    print(f"\nAdded {added_count} new cars across {len(added_per_decade)} decades:")
    for dec in sorted(added_per_decade.keys()):
        print(f"  {dec}: +{added_per_decade[dec]} cars")

    # 3. Save cars_metadata.json
    with open("cars_metadata.json", "w", encoding="utf-8") as f:
        json.dump(existing_cars, f, indent=2, ensure_ascii=False)
    print("\nSaved cars_metadata.json.")

    # 4. Save cars_metadata.csv with exact fieldnames
    fieldnames = [
        "Car name", "Manufacturer", "Exact model generation", "Model year",
        "Decade", "Country of manufacturer", "Vehicle category",
        "Image filename", "Original image URL", "Image source", "Image license/copyright information"
    ]
    with open("cars_metadata.csv", "w", newline="", encoding="utf-8") as f:
        writer = csv.DictWriter(f, fieldnames=fieldnames)
        writer.writeheader()
        for c in existing_cars:
            # write row ensuring all fields exist
            row = {fn: c.get(fn, "") for fn in fieldnames}
            writer.writerow(row)
    print("Saved cars_metadata.csv.")

    # 5. Save data/cars_metadata.js (for browser execution)
    js_content = f"window.CARS_METADATA = {json.dumps(existing_cars, ensure_ascii=False)};"
    with open("data/cars_metadata.js", "w", encoding="utf-8") as f:
        f.write(js_content)
    print("Saved data/cars_metadata.js.")

    # 6. Summary check
    df = pd.read_csv("cars_metadata.csv")
    print("\nFinal Master Dataset Summary:")
    print("Total vehicles:", len(df))
    print(df["Decade"].value_counts().sort_index())

if __name__ == "__main__":
    main()
